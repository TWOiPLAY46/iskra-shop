export function classifyProduct(name: string, sku: string = ''): CategoryClassification {
  if (!name || typeof name !== 'string') {
    return {
      mainCategory: 'Інше / Нерозподілені',
      subCategory: 'Нерозподілені',
      category: 'Інше'
    };
  }

  const text = `${name} ${sku}`.toLowerCase().trim().replace(/\s+/g, ' ');

  // 1. Check all prioritized rules from specific to general
  for (const rule of PRIORITY_RULES) {
    // Check if any keyword matches
    const matchedKeyword = rule.keywords.find((kw) => text.includes(kw));
    if (matchedKeyword) {
      // If there are exclude keywords, ensure none are present
      if (rule.excludeKeywords && rule.excludeKeywords.some((exKw) => text.includes(exKw))) {
        continue;
      }

      return {
        mainCategory: rule.mainCategory,
        subCategory: rule.subCategory,
        category: rule.category
      };
    }
  }

  // 2. Intelligent broad fallbacks if specific keyword was not matched directly
  if (text.includes('кабел') || text.includes('провід') || text.includes('провод') || text.includes('ввг') || text.includes('пвс')) {
    return {
      mainCategory: 'Електротовари',
      subCategory: 'Кабельна продукція',
      category: 'Кабель силовий ВВГ'
    };
  }

  if (text.includes('світил') || text.includes('светил') || text.includes('люстр') || text.includes('downlight')) {
    return {
      mainCategory: 'Електротовари',
      subCategory: 'Освітлення',
      category: 'Світильники'
    };
  }

  if (text.includes('ламп') || text.includes('лампочк') || text.includes('філамент')) {
    return {
      mainCategory: 'Електротовари',
      subCategory: 'Освітлення',
      category: 'Лампи LED'
    };
  }

  if (text.includes('кран') || text.includes('змішувач') || text.includes('смесител') || text.includes('сифон') || text.includes('підводк')) {
    return {
      mainCategory: 'Сантехніка та опалення',
      subCategory: 'Змішувачі та комплектуючі',
      category: 'Змішувач'
    };
  }

  if (text.includes('труб') || text.includes('фітинг') || text.includes('муфт') || text.includes('колін')) {
    return {
      mainCategory: 'Сантехніка та опалення',
      subCategory: 'Труби та фітинги',
      category: 'Труби'
    };
  }

  if (text.includes('інструмент') || text.includes('ключ') || text.includes('викрут') || text.includes('свердл')) {
    return {
      mainCategory: 'Інструменти та обладнання',
      subCategory: 'Ручний інструмент',
      category: 'Ручний інструмент'
    };
  }

  if (text.includes('дюбел') || text.includes('саморіз') || text.includes('шуруп') || text.includes('замок') || text.includes('кріплен')) {
    return {
      mainCategory: 'Господарчі товари',
      subCategory: 'Кріплення та фурнітура',
      category: 'Дюбелі та шурупи'
    };
  }

  // Fallback якщо жодне правило не підійшло
  return {
    mainCategory: 'Інше / Нерозподілені',
    subCategory: 'Нерозподілені',
    category: 'Інше'
  };
}
